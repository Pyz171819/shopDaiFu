            </el-form-item>
          </el-col>
          <el-col :span="24">
            <el-form-item label="变动金额" prop="money">
              <el-input v-model="form.money" placeholder="请输入变动金额" />
            </el-form-item>
          </el-col>
          <el-col :span="24">
            <el-form-item label="变动前余额" prop="beforeMoney">
              <el-input v-model="form.beforeMoney" placeholder="请输入变动前余额" />
            </el-form-item>
          </el-col>
          <el-col :span="24">
            <el-form-item label="变动后余额" prop="afterMoney">
              <el-input v-model="form.afterMoney" placeholder="请输入变动后余额" />
            </el-form-item>
          </el-col>
